import Foundation
import Security
import SecretsRuntime

/// On-disk obfuscation key material: the `.material` sidecar produced by `generate-key` and consumed
/// by `seal`. Holds the seed and salt as hex. It is the *obfuscation key*, not a secret — but treat it
/// as build input that both steps must share.
struct ObfuscationKeyMaterial: Codable {
    let seedHex: String
    let saltHex: String

    func obfuscationKey() throws -> SecretsObfuscationKey {
        guard let seed = Data(hexString: seedHex), !seed.isEmpty,
              let salt = Data(hexString: saltHex), !salt.isEmpty else {
            throw SecretCompilerError.invalidKeyMaterial("seed/salt must be non-empty hex")
        }
        return SecretsObfuscationKey(seed: Array(seed), salt: Array(salt))
    }

    static func generate() throws -> ObfuscationKeyMaterial {
        return ObfuscationKeyMaterial(seedHex: try randomHex(32), saltHex: try randomHex(32))
    }

    static func load(from path: String) throws -> ObfuscationKeyMaterial {
        let data = try Data(contentsOf: URL(fileURLWithPath: path))
        guard let material = try? JSONDecoder().decode(ObfuscationKeyMaterial.self, from: data) else {
            throw SecretCompilerError.invalidKeyMaterial(path)
        }
        return material
    }

    /// Renders the Swift source compiled into the app binary. Contains the key, not the secrets.
    func swiftSource(symbol: String) -> String {
        let seed = Data(hexString: seedHex) ?? Data()
        let salt = Data(hexString: saltHex) ?? Data()
        let seedList = seed.map { String($0) }.joined(separator: ", ")
        let saltList = salt.map { String($0) }.joined(separator: ", ")
        return """
        // Generated by `secretcompiler generate-key`. Do not edit.
        //
        // This file holds the OBF3 obfuscation key compiled into your app binary. It does NOT contain
        // your secrets. It is per-app (not per-build): generate it once, commit it to your app repo,
        // and pass the matching .material file to `seal`.
        import SecretsRuntime

        enum \(symbol) {
            static let seed: [UInt8] = [\(seedList)]
            static let salt: [UInt8] = [\(saltList)]
            static var obfuscationKey: SecretsObfuscationKey { SecretsObfuscationKey(seed: seed, salt: salt) }
        }
        """
    }

    private static func randomHex(_ count: Int) throws -> String {
        var bytes = [UInt8](repeating: 0, count: count)
        guard SecRandomCopyBytes(kSecRandomDefault, count, &bytes) == errSecSuccess else {
            throw SecretCompilerError.invalidKeyMaterial("random generation failed")
        }
        return bytes.map { String(format: "%02x", $0) }.joined()
    }
}
